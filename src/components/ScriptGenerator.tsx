import React, { useState } from 'react';
import { PipelineSettings } from '../types';
import { getEpisodesBySeasonAndDisc, formatPlexName } from '../data/ncisCatalog';
import {
  Terminal,
  Download,
  Copy,
  Check,
  FolderCog,
  FileCode,
  ShieldAlert,
  Play,
  Settings2,
} from 'lucide-react';

interface ScriptGeneratorProps {
  selectedSeason: number;
  selectedDisc: number;
  settings: PipelineSettings;
  setSettings: React.Dispatch<React.SetStateAction<PipelineSettings>>;
}

export const ScriptGenerator: React.FC<ScriptGeneratorProps> = ({
  selectedSeason,
  selectedDisc,
  settings,
  setSettings,
}) => {
  const episodes = getEpisodesBySeasonAndDisc(selectedSeason, selectedDisc);
  const [activeScriptType, setActiveScriptType] = useState<'pipeline_ps1' | 'rename_ps1' | 'batch_cmd'>('pipeline_ps1');
  const [copied, setCopied] = useState(false);

  const sStr = String(selectedSeason).padStart(2, '0');

  // Generate Full PowerShell Automation Pipeline Script
  const generatePowerShellPipelineScript = () => {
    const encoder = settings.videoCodec === 'x265_10bit' ? 'x265_10bit' : 'x264';
    const decombArgs =
      settings.decombFilter === 'decomb'
        ? '--comb-detect --decomb'
        : settings.decombFilter === 'yadif'
        ? '--deinterlace=yadif'
        : '';

    const audioArgs = settings.addAacStereoFallback
      ? '-a 1,1 -E copy:ac3,av_aac -B 0,160 -6 0,dpl2'
      : '-a 1 -E copy:ac3';

    const subArgs = settings.subtitleMode === 'embed_vobsub' ? '-s "1,2" --subtitle-burned=none' : '';

    const trackMappings = episodes
      .map((ep, idx) => {
        const sourceFile = `title_t0${idx}.mkv`;
        const plexName = formatPlexName(ep);
        return `    @{ Source = "${sourceFile}"; Target = "${plexName}"; Title = "${ep.title}"; Episode = "E${String(
          ep.episode
        ).padStart(2, '0')}" }`;
      })
      .join(',\n');

    return `# =====================================================================
# NCIS Season ${selectedSeason} Disc ${selectedDisc} - Automated HandBrake & Plex Pipeline
# Generated by NCIS DVD-to-Plex Automation Studio
# =====================================================================

param (
    [string]$SourceDir = "${settings.sourceDirectory}",
    [string]$PlexRootDir = "${settings.plexLibraryDirectory}",
    [string]$HandBrakeCliPath = "${settings.handbrakeCliPath}",
    [switch]$Overwrite = $false
)

$ErrorActionPreference = "Stop"

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host "  NCIS Season ${selectedSeason} Disc ${selectedDisc} Batch Encoder & Plex Renamer" -ForegroundColor Cyan
Write-Host "  Idempotent mode: Existing Plex episodes will be skipped" -ForegroundColor DarkCyan
Write-Host "==========================================================" -ForegroundColor Cyan

# 1. Locate HandBrakeCLI
if (-not (Test-Path $HandBrakeCliPath)) {
    # Attempt automatic lookup in standard paths or PATH
    $cmd = Get-Command "HandBrakeCLI.exe" -ErrorAction SilentlyContinue
    if ($cmd) {
        $HandBrakeCliPath = $cmd.Source
    } elseif (Test-Path "C:\\Program Files\\HandBrake\\HandBrakeCLI.exe") {
        $HandBrakeCliPath = "C:\\Program Files\\HandBrake\\HandBrakeCLI.exe"
    } else {
        Write-Error "HandBrakeCLI.exe not found at '$HandBrakeCliPath'. Please install HandBrake or specify its path."
        exit 1
    }
}
Write-Host "Using HandBrakeCLI at: $HandBrakeCliPath" -ForegroundColor Green

# 2. Verify Source Directory
if (-not (Test-Path $SourceDir)) {
    Write-Warning "Source directory '$SourceDir' not found."
    $SourceDir = Read-Host "Please enter the folder where MakeMKV saved raw tracks"
}

# 3. Create Target Plex Season Directory
$TargetSeasonDir = Join-Path -Path $PlexRootDir -ChildPath "NCIS (2003)\\Season ${sStr}"
if (-not (Test-Path $TargetSeasonDir)) {
    Write-Host "Creating Plex directory: $TargetSeasonDir" -ForegroundColor Yellow
    New-Item -ItemType Directory -Path $TargetSeasonDir -Force | Out-Null
} else {
    Write-Host "Plex destination folder: $TargetSeasonDir" -ForegroundColor Green
}

# 4. Disc Track to Canonical Plex Episode Mapping
$Episodes = @(
${trackMappings}
)

# 5. Process Episodes
$total = $Episodes.Count
$current = 0
$skipped = 0
$encoded = 0

foreach ($item in $Episodes) {
    $current++
    $inputFile = Join-Path -Path $SourceDir -ChildPath $item.Source
    $outputFile = Join-Path -Path $TargetSeasonDir -ChildPath $item.Target

    Write-Host ""
    Write-Host "----------------------------------------------------------" -ForegroundColor DarkGray
    Write-Host "[$current / $total] Processing $($item.Episode): $($item.Title)" -ForegroundColor Yellow
    Write-Host "Source: $inputFile" -ForegroundColor Gray
    Write-Host "Target: $outputFile" -ForegroundColor Cyan

    # Idempotent re-run check: skip if file already exists in Plex and is non-empty (>25MB)
    if (Test-Path $outputFile) {
        $existingItem = Get-Item $outputFile
        $existingSizeMb = [math]::Round($existingItem.Length / 1MB, 1)
        if (-not $Overwrite -and $existingItem.Length -gt 25MB) {
            Write-Host "  [IDEMPOTENT] Already exists in Plex: $($item.Target) ($existingSizeMb MB) - Skipping encode." -ForegroundColor Green
            $skipped++
            continue
        } else {
            Write-Host "  Overwriting existing file: $($item.Target)" -ForegroundColor Yellow
        }
    }

    if (-not (Test-Path $inputFile)) {
        Write-Warning "Input file '$($item.Source)' not found in '$SourceDir'. Skipping this track."
        continue
    }

    # Execute HandBrakeCLI with NTSC DVD Decomb and Plex Settings
    $hbArgs = @(
        "-i", $inputFile,
        "-o", $outputFile,
        "-e", "${encoder}",
        "-q", "${settings.rfQuality}",
        "--rate", "29.97",
        "--pfr",
        "--auto-anamorphic",
        "--markers",
        "--optimize",
        ${settings.decombFilter === 'decomb' ? '"--comb-detect", "--decomb",' : settings.decombFilter === 'yadif' ? '"--deinterlace=yadif",' : ''}
        ${settings.addAacStereoFallback ? '"-a", "1,1", "-E", "copy:ac3,av_aac", "-B", "0,160", "-6", "0,dpl2",' : '"-a", "1", "-E", "copy:ac3",'}
        ${settings.subtitleMode === 'embed_vobsub' ? '"-s", "1,2", "--subtitle-burned=none",' : ''}
        "--encoder-preset", "slow"
    )

    $stopwatch = [System.Diagnostics.Stopwatch]::StartNew()
    & $HandBrakeCliPath $hbArgs

    $stopwatch.Stop()
    $elapsedMinutes = [math]::Round($stopwatch.Elapsed.TotalMinutes, 1)

    if ($LASTEXITCODE -eq 0) {
        Write-Host "Successfully encoded in $elapsedMinutes mins: $($item.Target)" -ForegroundColor Green
        $encoded++
    } else {
        Write-Error "HandBrake failed on $($item.Source) with exit code $LASTEXITCODE"
    }
}

Write-Host ""
Write-Host "==========================================================" -ForegroundColor Green
if ($skipped -gt 0) {
    Write-Host "  Disc Complete! $encoded newly encoded, $skipped skipped (idempotent)." -ForegroundColor Green
} else {
    Write-Host "  Disc Complete! All $encoded episodes ready for Plex library scanner." -ForegroundColor Green
}
Write-Host "==========================================================" -ForegroundColor Green
`;
  };

  // Generate Pure Renamer PowerShell Script (for already-encoded files)
  const generatePowerShellRenameScript = () => {
    const trackRenames = episodes
      .map((ep, idx) => {
        const sourceFile = `title_t0${idx}.mkv`;
        const plexName = formatPlexName(ep);
        return `    @{ OldName = "${sourceFile}"; NewName = "${plexName}" }`;
      })
      .join(',\n');

    return `# =====================================================================
# NCIS Season ${selectedSeason} Disc ${selectedDisc} - Fast Plex File Renamer
# Use this if you already encoded tracks in HandBrake GUI and need instant Plex names!
# Idempotent: Skips files already renamed.
# =====================================================================

param (
    [string]$Folder = "${settings.sourceDirectory}"
)

Write-Host "Renaming files in: $Folder" -ForegroundColor Cyan

$Mappings = @(
${trackRenames}
)

foreach ($map in $Mappings) {
    $fullOldPath = Join-Path $Folder $map.OldName
    $fullNewPath = Join-Path $Folder $map.NewName

    if (Test-Path $fullNewPath) {
        $destSizeMb = [math]::Round((Get-Item $fullNewPath).Length / 1MB, 1)
        Write-Host "  [IDEMPOTENT] Target already exists: $($map.NewName) ($destSizeMb MB) - Skipping rename." -ForegroundColor Green
    } elseif (Test-Path $fullOldPath) {
        Write-Host "  Renaming: $($map.OldName) -> $($map.NewName)" -ForegroundColor Yellow
        Rename-Item -Path $fullOldPath -NewName $map.NewName
        Write-Host "  Done!" -ForegroundColor Green
    } else {
        Write-Warning "  File not found: $($map.OldName) (Skipping)"
    }
}

Write-Host "Renaming completed for Disc ${selectedDisc}!" -ForegroundColor Cyan
`;
  };

  // Generate Classic Windows Batch (.bat) Script
  const generateBatchScript = () => {
    const trackCommands = episodes
      .map((ep, idx) => {
        const sourceFile = `title_t0${idx}.mkv`;
        const plexName = formatPlexName(ep);
        return `echo.
if not "%OVERWRITE%"=="1" if exist "%TARGET_DIR%\\${plexName}" (
    echo [IDEMPOTENT] [%idx%/${episodes.length}] Already exists in Plex: ${plexName} - Skipping.
    goto skip_${idx}
)
echo [${idx + 1}/${episodes.length}] Encoding ${ep.title}...
"%HB_CLI%" -i "%SOURCE_DIR%\\${sourceFile}" -o "%TARGET_DIR%\\${plexName}" -e x264 -q ${settings.rfQuality} --rate 29.97 --pfr --auto-anamorphic --comb-detect --decomb -a 1 -E copy:ac3 --markers --optimize
:skip_${idx}`;
      })
      .join('\n');

    return `@echo off
rem =====================================================================
rem NCIS Season ${selectedSeason} Disc ${selectedDisc} Batch Encoder
rem Set OVERWRITE=1 to force re-encoding of existing files.
rem =====================================================================

set "SOURCE_DIR=${settings.sourceDirectory}"
set "TARGET_DIR=${settings.plexLibraryDirectory}\\NCIS (2003)\\Season ${sStr}"
set "HB_CLI=${settings.handbrakeCliPath}"
set "OVERWRITE=0"

echo ==========================================================
echo NCIS Season ${selectedSeason} Disc ${selectedDisc} Batch Pipeline (Idempotent)
echo ==========================================================

if not exist "%TARGET_DIR%" (
    echo Creating target directory: %TARGET_DIR%
    mkdir "%TARGET_DIR%"
)

${trackCommands}

echo.
echo ==========================================================
echo Finished encoding all episodes for Disc ${selectedDisc}!
echo ==========================================================
pause
`;
  };

  const currentScriptContent =
    activeScriptType === 'pipeline_ps1'
      ? generatePowerShellPipelineScript()
      : activeScriptType === 'rename_ps1'
      ? generatePowerShellRenameScript()
      : generateBatchScript();

  const copyScriptToClipboard = () => {
    navigator.clipboard.writeText(currentScriptContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const downloadScriptFile = () => {
    const ext = activeScriptType === 'batch_cmd' ? 'bat' : 'ps1';
    const filename =
      activeScriptType === 'pipeline_ps1'
        ? `Encode-NCIS-S${sStr}D${selectedDisc}.${ext}`
        : activeScriptType === 'rename_ps1'
        ? `Rename-NCIS-S${sStr}D${selectedDisc}.${ext}`
        : `Encode-NCIS-S${sStr}D${selectedDisc}.${ext}`;

    const blob = new Blob([currentScriptContent], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {/* Path Configuration Form */}
      <div className="bg-slate-900 border border-slate-800 rounded-xl p-5 space-y-4">
        <div className="flex items-center gap-2 pb-2 border-b border-slate-800">
          <FolderCog className="w-4 h-4 text-amber-400" />
          <h3 className="text-sm font-bold text-white uppercase tracking-wider">
            Windows Directory Paths Configuration
          </h3>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
          <div>
            <label className="block text-xs font-semibold text-slate-300 mb-1">
              MakeMKV Rips Source Folder
            </label>
            <input
              type="text"
              value={settings.sourceDirectory}
              onChange={(e) => setSettings({ ...settings, sourceDirectory: e.target.value })}
              className="w-full text-xs font-mono bg-slate-950 border border-slate-700 rounded-lg px-3 py-2 text-slate-200 focus:ring-1 focus:ring-amber-500"
              placeholder="D:\MakeMKV_Rips\NCIS_S01_D1"
            />
            <p className="text-[10px] text-slate-400 mt-1">
              Folder where MakeMKV outputs title_t00.mkv
            </p>
          </div>

          <div>
            <label className="block text-xs font-semibold text-slate-300 mb-1">
              Plex TV Library Destination
            </label>
            <input
              type="text"
              value={settings.plexLibraryDirectory}
              onChange={(e) =>
                setSettings({ ...settings, plexLibraryDirectory: e.target.value })
              }
              className="w-full text-xs font-mono bg-slate-950 border border-slate-700 rounded-lg px-3 py-2 text-slate-200 focus:ring-1 focus:ring-amber-500"
              placeholder="X:\Media\TV Shows"
            />
            <p className="text-[10px] text-slate-400 mt-1">
              Appends \NCIS (2003)\Season {sStr} automatically
            </p>
          </div>

          <div>
            <label className="block text-xs font-semibold text-slate-300 mb-1">
              HandBrakeCLI.exe Path
            </label>
            <input
              type="text"
              value={settings.handbrakeCliPath}
              onChange={(e) => setSettings({ ...settings, handbrakeCliPath: e.target.value })}
              className="w-full text-xs font-mono bg-slate-950 border border-slate-700 rounded-lg px-3 py-2 text-slate-200 focus:ring-1 focus:ring-amber-500"
              placeholder="C:\Program Files\HandBrake\HandBrakeCLI.exe"
            />
            <p className="text-[10px] text-slate-400 mt-1">
              Script auto-checks standard Program Files location
            </p>
          </div>
        </div>
      </div>

      {/* Script Selector Tabs & Action Bar */}
      <div className="bg-slate-900 border border-slate-800 rounded-xl p-5 space-y-4">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-slate-800">
          {/* Script Type Tabs */}
          <div className="flex items-center gap-1.5 p-1 bg-slate-950 rounded-lg border border-slate-800">
            <button
              onClick={() => setActiveScriptType('pipeline_ps1')}
              className={`px-3 py-1.5 text-xs font-medium rounded-md transition-colors ${
                activeScriptType === 'pipeline_ps1'
                  ? 'bg-amber-500 text-slate-950 font-bold'
                  : 'text-slate-300 hover:text-white'
              }`}
            >
              Full Automated Pipeline (.ps1)
            </button>
            <button
              onClick={() => setActiveScriptType('rename_ps1')}
              className={`px-3 py-1.5 text-xs font-medium rounded-md transition-colors ${
                activeScriptType === 'rename_ps1'
                  ? 'bg-amber-500 text-slate-950 font-bold'
                  : 'text-slate-300 hover:text-white'
              }`}
            >
              Pure Plex Renamer (.ps1)
            </button>
            <button
              onClick={() => setActiveScriptType('batch_cmd')}
              className={`px-3 py-1.5 text-xs font-medium rounded-md transition-colors ${
                activeScriptType === 'batch_cmd'
                  ? 'bg-amber-500 text-slate-950 font-bold'
                  : 'text-slate-300 hover:text-white'
              }`}
            >
              Classic Command Prompt (.bat)
            </button>
          </div>

          {/* Action Buttons */}
          <div className="flex items-center gap-2">
            <button
              onClick={copyScriptToClipboard}
              className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 rounded-lg transition-colors"
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-400" />
                  <span className="text-emerald-400">Copied Script!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" />
                  <span>Copy Script</span>
                </>
              )}
            </button>

            <button
              onClick={downloadScriptFile}
              className="flex items-center gap-1.5 px-3.5 py-1.5 text-xs font-semibold bg-amber-500 hover:bg-amber-400 text-slate-950 rounded-lg transition-colors shadow-sm"
            >
              <Download className="w-3.5 h-3.5" />
              <span>
                Download {activeScriptType === 'batch_cmd' ? '.bat' : '.ps1'}
              </span>
            </button>
          </div>
        </div>

        {/* Script Viewer */}
        <div>
          <div className="flex items-center justify-between text-xs text-slate-400 font-mono mb-2">
            <span className="flex items-center gap-1.5 text-slate-300">
              <FileCode className="w-3.5 h-3.5 text-amber-400" />
              {activeScriptType === 'pipeline_ps1'
                ? `Encode-NCIS-S${sStr}D${selectedDisc}.ps1 (Batch transcode + Decomb + Direct Plex Output)`
                : activeScriptType === 'rename_ps1'
                ? `Rename-NCIS-S${sStr}D${selectedDisc}.ps1 (Instant rename for already-encoded files)`
                : `Encode-NCIS-S${sStr}D${selectedDisc}.bat (Command Prompt runner)`}
            </span>
            <span>Targeting {episodes.length} episodes for Disc {selectedDisc}</span>
          </div>

          <pre className="p-4 bg-slate-950 rounded-lg border border-slate-800 font-mono text-xs text-amber-200/90 overflow-x-auto max-h-[460px] scrollbar-thin whitespace-pre leading-relaxed">
            {currentScriptContent}
          </pre>
        </div>

        {/* PowerShell Execution Hint */}
        <div className="bg-slate-950 border border-slate-800 rounded-lg p-3.5 text-xs text-slate-300 space-y-2">
          <div className="flex items-center gap-2 font-semibold text-amber-300">
            <ShieldAlert className="w-4 h-4 text-amber-400 shrink-0" />
            <span>How to Run in Windows PowerShell:</span>
          </div>
          <p className="text-slate-400">
            If Windows blocks running PowerShell scripts with an execution policy error, simply open PowerShell and run:
          </p>
          <div className="bg-slate-900 px-3 py-1.5 rounded font-mono text-amber-300/90 border border-slate-800 select-all">
            Set-ExecutionPolicy -Scope Process -ExecutionPolicy Bypass
          </div>
          <p className="text-slate-400">
            Then execute your script by typing: <span className="font-mono text-slate-200">.\Encode-NCIS-S{sStr}D{selectedDisc}.ps1</span>
          </p>
        </div>
      </div>
    </div>
  );
};
